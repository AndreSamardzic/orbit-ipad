export const L: Record<Lang, Record<VKey, string>> = { de, en }

export function fill(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (_m, k: string) => (k in vars ? String(vars[k]) : `{${k}}`))
}

export const vt = (lang: Lang, k: VKey, vars?: Record<string, string | number>): string => fill(L[lang][k], vars)
